import { jsPDF } from 'jspdf'
import { formatDate } from './helpers'

export function generateAnalysisPdf(detail) {
  const doc = new jsPDF()
  const margin = 20
  let y = margin

  const addLine = (text, size = 11, bold = false) => {
    doc.setFontSize(size)
    doc.setFont('helvetica', bold ? 'bold' : 'normal')
    const lines = doc.splitTextToSize(text, 170)
    if (y + lines.length * (size * 0.45) > 280) {
      doc.addPage()
      y = margin
    }
    doc.text(lines, margin, y)
    y += lines.length * (size * 0.45) + 4
  }

  doc.setFillColor(15, 15, 25)
  doc.rect(0, 0, 210, 40, 'F')
  doc.setTextColor(255, 255, 255)
  doc.setFontSize(18)
  doc.setFont('helvetica', 'bold')
  doc.text('YouTube Authenticity Analyzer', margin, 18)
  doc.setFontSize(10)
  doc.setFont('helvetica', 'normal')
  doc.text('Credibility Assessment Report', margin, 28)

  y = 52
  doc.setTextColor(30, 30, 30)

  addLine('Analysis Overview', 16, true)
  y += 4

  const resultLabel =
    detail.result === 'credible'
      ? 'Credible Content ✅'
      : detail.result === 'suspicious'
        ? 'Suspicious Content ⚠️'
        : 'Analysis Error'

  const words = detail.word_count ?? detail.transcript_length ?? (detail.full_content ? detail.full_content.split(/\s+/).length : 0)
  const chars = detail.character_count ?? (detail.full_content ? detail.full_content.length : 0)

  const fields = [
    ['Analysis ID', `#${detail.id}`],
    ['Date / Time', formatDate(detail.created_at || detail.date_time)],
    ['Analysis Type', detail.analysis_type ? detail.analysis_type.toUpperCase() : 'N/A'],
    ['Prediction Result', resultLabel],
    ['Confidence Score', detail.confidence_score != null ? `${detail.confidence_score}%` : 'N/A'],
    ['Risk Level', detail.risk_level || (detail.result === 'credible' ? 'Low Risk' : 'High Risk')],
    ['Word Count', `${words.toLocaleString()} words`],
    ['Character Count', `${chars.toLocaleString()} characters`],
    ['Original URL', detail.youtube_url || 'N/A'],
  ]

  fields.forEach(([label, value]) => {
    addLine(`${label}: ${value}`, 11, false)
  })

  if (detail.recommendation) {
    y += 4
    addLine('Recommendation:', 12, true)
    addLine(detail.recommendation, 10, false)
  }

  if (detail.indicators?.length) {
    y += 4
    addLine('Indicators Detected:', 12, true)
    detail.indicators.forEach((ind) => addLine(`• ${ind}`, 10, false))
  }

  doc.setFontSize(8)
  doc.setTextColor(120, 120, 120)
  doc.text('Generated by YouTube Authenticity Analyzer · Suspicious content detected by the model. Further verification recommended.', margin, 290)

  const filename = `analysis-report-${detail.id}.pdf`
  doc.save(filename)
}
